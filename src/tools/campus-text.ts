export function useCampusText() {
  const { locale } = useI18n();
  return (chinese: string, english: string) => {
    const activeLocale = locale.value.toLowerCase();
    if (activeLocale.startsWith('zh')) {
      return chinese;
    }
    if (activeLocale.startsWith('ru')) {
      const overdue = english.match(/^(\d+) days overdue$/);
      if (overdue) {
        return `Просрочено на ${overdue[1]} ${russianDayWord(Number(overdue[1]))}`;
      }

      const daysLeft = english.match(/^(\d+) days left$/);
      if (daysLeft) {
        return `Осталось ${daysLeft[1]} ${russianDayWord(Number(daysLeft[1]))}`;
      }

      const week = english.match(/^Week (\d+)$/);
      if (week) {
        return `Неделя ${week[1]}`;
      }

      if (english.startsWith('Consider adding available details: ')) {
        return `При наличии дополните сведения: ${english.slice('Consider adding available details: '.length)}`;
      }

      return russianCampusText[english] ?? english;
    }
    return english;
  };
}

function russianDayWord(days: number) {
  const lastTwoDigits = days % 100;
  if (lastTwoDigits >= 11 && lastTwoDigits <= 14) {
    return 'дней';
  }
  switch (days % 10) {
    case 1: return 'день';
    case 2:
    case 3:
    case 4: return 'дня';
    default: return 'дней';
  }
}

export function makeCampusId(prefix: string) {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}
